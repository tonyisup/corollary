"""Event schemas for the Corollary message bus.

All event types are Pydantic models with Literal type discriminators,
compatible with an async queue / future gRPC transport.
"""

from __future__ import annotations

from pydantic import BaseModel, Field
from typing import List, Literal, Optional, Union


# ─── Audio pipeline ────────────────────────────────────────────────────────

class AudioFrame(BaseModel):
    """Raw PCM frame from microphone or TTS tap."""
    type: Literal["audio_frame"] = "audio_frame"
    stream_id: str                      # "mic-1", "tts-out", etc.
    ts_ms: int
    sr: int = 16000
    format: Literal["f32", "s16"] = "f32"
    pcm_base64: str                     # float32 PCM, little-endian, base64


class EffCopyFrame(BaseModel):
    """Efference copy — predicted mel features from TTS output.

    Generated by the Cerebellum before audio reaches the speakers.
    The Thalamus uses this to gate matching mic input.
    """
    type: Literal["eff_copy_frame"] = "eff_copy_frame"
    utterance_id: str
    ts_ms: int
    sr: int = 16000
    mel: "MelBlock"


class MelBlock(BaseModel):
    n_mels: int = 80
    frame_idx: int
    values: list[float]                 # row-major mel frame (n_mels,)


# ─── Perception pipeline ───────────────────────────────────────────────────

class ASRToken(BaseModel):
    """Single token from streaming ASR after thalamus gating."""
    type: Literal["asr_token"] = "asr_token"
    ts_ms: int
    speaker: Literal["self", "world", "unknown"]
    token: str
    logprob: float
    segment_id: str
    source: str = "stg"


class Utterance(BaseModel):
    """Attributed spoken utterance (aggregated tokens)."""
    type: Literal["utterance"] = "utterance"
    channel: str                        # "mic" | "internal"
    speaker_id: str                     # "spk#2" | "self"
    text: str
    start_ms: int
    end_ms: int
    confidence: float
    diarization: Optional["DiarizationInfo"] = None


class DiarizationInfo(BaseModel):
    speaker_label: str                  # e.g. "A", "B" (pyannote label)
    turn_idx: int


# ─── Memory ────────────────────────────────────────────────────────────────

class MemoryEvent(BaseModel):
    """Episodic or semantic memory write."""
    type: Literal["memory_event"] = "memory_event"
    kind: Literal["episodic", "semantic"]
    key: str                            # unique identifier
    ts_ms: int
    embedding: Optional[list[float]] = None
    payload: "MemoryPayload"


class MemoryPayload(BaseModel):
    text: str
    who: str                            # "user" | "self" | "system"
    where: str                          # context label
    salience: float = Field(ge=0.0, le=1.0, default=0.5)


# ─── Control ───────────────────────────────────────────────────────────────

class LoopIndex(BaseModel):
    """Health check — self-trigger rate monitor."""
    type: Literal["loop_index"] = "loop_index"
    ts_ms: int
    self_trigger_rate: float            # 0.0 = healthy, >0.1 = concerning
    cooldown_active: bool = False


# Update forward refs
EffCopyFrame.model_rebuild()
Utterance.model_rebuild()
MemoryEvent.model_rebuild()


# ─── Union type for dispatch ──────────────────────────────────────────────

BusEvent = Union[
    AudioFrame, EffCopyFrame, ASRToken, Utterance, MemoryEvent, LoopIndex
]
